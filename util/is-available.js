// Признак «книгу можно купить» нужен и шаблонам, и контроллеру корзины —
// правило живёт в одном месте, чтобы витрина и сервер не разъехались.
// Книги, заведённые до появления поля, поля не имеют и остаются в продаже:
// снимать их с продажи молча было бы потерей данных.
function isAvailable(product) {
  return Boolean(product) && product.available !== false;
}

module.exports = isAvailable;
